// Downloads 18th Avenue's own media from the live site and writes web-ready masters to public/media.
// Usage: node scripts/fetch-assets.mjs   (re-runs skip files already downloaded to assets-src/)
import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(import.meta.dirname, '..');
const manifest = JSON.parse(await fs.readFile(path.join(root, 'scripts/assets.json'), 'utf8'));
const SRC = path.join(root, 'assets-src');
const OUT = path.join(root, 'public/media');

// Line art (plans, maps, logos) stays lossless so thin walls and labels don't smear.
const LOSSLESS = new Set(['plans', 'consultants']);
const MAX_W = 2560;

async function exists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function download(url, dest) {
  if (await exists(dest)) return;
  const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 (asset pipeline)' } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  await fs.writeFile(dest, Buffer.from(await res.arrayBuffer()));
}

const meta = {};
for (const [group, items] of Object.entries(manifest.groups)) {
  await fs.mkdir(path.join(SRC, group), { recursive: true });
  await fs.mkdir(path.join(OUT, group), { recursive: true });
  meta[group] = {};
  for (const [name, rel] of Object.entries(items)) {
    const ext = path.extname(rel);
    const raw = path.join(SRC, group, name + ext);
    await download(manifest.base + rel, raw);

    const out = path.join(OUT, group, `${name}.webp`);
    let img = sharp(raw).rotate();
    const { width } = await img.metadata();
    if (width > MAX_W) img = img.resize({ width: MAX_W });
    if (group === 'consultants') img = img.flatten({ background: '#ffffff' });
    const info = await img
      .webp(LOSSLESS.has(group) ? { lossless: true, effort: 5 } : { quality: 86, effort: 5, smartSubsample: true })
      .toFile(out);
    meta[group][name] = { src: `/media/${group}/${name}.webp`, width: info.width, height: info.height, source: manifest.base + rel };
    console.log(`${group}/${name}  ${info.width}×${info.height}  ${(info.size / 1024).toFixed(0)} KB`);
  }
}

const ts = `// Generated by scripts/fetch-assets.mjs. Do not edit by hand.
// Every file is 18th Avenue's own media, downloaded from 18thavenue.com.bn (artist's impressions).
export type Media = { src: string; width: number; height: number; source: string };

export const media = ${JSON.stringify(meta, null, 2)} as const satisfies Record<string, Record<string, Media>>;
`;
await fs.writeFile(path.join(root, 'src/content/media.ts'), ts);
console.log('wrote src/content/media.ts');
